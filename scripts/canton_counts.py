#!/usr/bin/env python3
"""Recount companies per canton from data/ and rewrite the totals in index.html.

The canton list shows these totals before a canton is loaded, so they must
match what the app draws: rows with a legal form and non-zero coordinates
(the same filter as the parse worker).

Usage:
  python3 scripts/canton_counts.py
"""

import glob
import gzip
import json
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..")
BEGIN, END = "// counts:begin", "// counts:end"


def count_canton(canton_id):
    total = 0
    for path in sorted(glob.glob(os.path.join(ROOT, "data", f"{canton_id}_*.json.gz"))):
        with gzip.open(path, "rt", encoding="utf-8") as f:
            col = json.load(f)
        for t, lat, lng in zip(col["t"], col["lat"], col["lng"]):
            if (t or "").strip() and lat and lng:
                total += 1
    return total


def main():
    ids = sorted(
        os.path.basename(p)[:-5]
        for p in glob.glob(os.path.join(ROOT, "data", "??.json"))
    )
    counts = {cid: count_canton(cid) for cid in ids}

    html_path = os.path.join(ROOT, "index.html")
    html = open(html_path, encoding="utf-8").read()
    m = re.search(rf"^([ \t]*){re.escape(BEGIN)}[^\n]*\n.*?^\s*{re.escape(END)}", html, re.S | re.M)
    if not m:
        raise SystemExit(f"markers {BEGIN} / {END} not found in index.html")
    indent = m.group(1)
    body = "\n".join(f"{indent}    {cid}: {n}," for cid, n in counts.items())
    block = f"{indent}{BEGIN} — generated by scripts/canton_counts.py\n{indent}const cantonCounts = {{\n{body}\n{indent}}};\n{indent}{END}"
    html = html[: m.start()] + block + html[m.end():]
    open(html_path, "w", encoding="utf-8").write(html)

    print(f"{len(counts)} cantons, {sum(counts.values()):,} companies")


if __name__ == "__main__":
    main()
